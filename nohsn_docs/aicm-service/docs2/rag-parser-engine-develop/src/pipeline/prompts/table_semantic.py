"""테이블 시맨틱 분석 프롬프트.

표의 구조적 특성과 의미를 파악한다: 표 유형, 컬럼 타입, 집계 여부, 요약 설명.

Version: 1.0.0 (A/B 테스트용 버전 관리)
"""

from __future__ import annotations

PROMPT_VERSION = "1.0.0"


def build_table_analysis_prompt(table_markdown: str, context: str) -> str:
    """테이블 시맨틱 분석 프롬프트를 생성한다.

    Args:
        table_markdown: 마크다운 형식의 표 내용.
        context: 표 주변 텍스트 (캡션, 앞뒤 문단 등).

    Returns:
        LLM에 전달할 프롬프트 문자열.
    """
    return f"""당신은 데이터 분석 전문가입니다. 아래 표의 구조와 의미를 분석하세요.

## 분석 항목

### 1. table_type (표 유형)
다음 중 하나를 선택하세요:
- `data`: 데이터 테이블 (수치, 측정값, 통계 등 데이터가 주 내용)
- `comparison`: 비교표 (제품/옵션/방안 등을 항목별로 비교)
- `schedule`: 일정표 (시간, 날짜, 기간 기반의 계획/진행)
- `specification`: 사양표 (제품/시스템의 기술적 속성 나열)
- `summary`: 요약표 (카테고리별 현황, 집계 결과)
- `matrix`: 매트릭스 (행과 열 모두 의미 있는 교차 분석표)

### 2. column_types (컬럼 타입)
각 컬럼의 데이터 성격을 판단하세요:
- `numeric`: 숫자, 수량, 금액, 비율, 측정값
- `text`: 일반 텍스트, 설명, 비고
- `date`: 날짜, 기간, 시간
- `category`: 분류, 구분, 유형 (유한한 카테고리 값)
- `id`: 번호, 순번, 코드, 식별자

### 3. has_aggregation (집계 여부)
표에 합계, 평균, 소계 등 집계 행/열이 있는지 판단하세요.
"합계", "소계", "Total", "Sum", "평균", "계" 등의 키워드가 단서입니다.

### 4. description (표 설명)
표의 내용을 검색에 유용한 한 문장으로 요약하세요 (한국어).

### 5. table_nl (자연어 해석 — 3~5 문장)
표의 각 행/열 관계를 실제 상담·질의응답에서 쓰기 좋게 자연어로 풀어 쓰세요.
숫자가 있는 표는 **핵심 수치를 본문에 직접 포함**하고, 비교표는 항목간 차이를 서술하며,
절차/일정 표는 순서/시점을 문장으로 나열하세요.
검색 임베딩과 RAG 답변 생성에 모두 사용되므로 **표 없이도 이 글만 읽고 답할 수 있어야** 합니다.

## 출력 형식

JSON 객체만 반환하세요. 다른 텍스트, 마크다운 펜스, 주석 없이 순수 JSON 만 출력.

{{
  "table_type": "data",
  "column_types": [
    {{"name": "연도", "type": "date"}},
    {{"name": "매출액", "type": "numeric"}},
    {{"name": "비고", "type": "text"}}
  ],
  "has_aggregation": true,
  "description": "2020-2024년 연도별 매출액 추이와 전년 대비 성장률",
  "table_nl": "2020년부터 2024년까지의 연간 매출액 추이를 정리한 표입니다. 2020년 100억원에서 시작하여 2024년 150억원으로 약 50% 성장했으며, 특히 2022년에는 전년 대비 18% 증가로 가장 높은 성장률을 기록했습니다. 비고란에는 신제품 출시, 시장 확장 등의 주요 이벤트가 기록되어 있습니다."
}}

## 주변 맥락

{context}

## 표 내용 (Markdown)

{table_markdown}"""
